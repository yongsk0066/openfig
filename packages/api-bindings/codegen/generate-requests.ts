import { file_fig as file } from "@fig/proto/fig";
import { CodeBlockWriter, IndentationText, Project } from "ts-morph";
import { readFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const codegenDirectory = dirname(fileURLToPath(import.meta.url));

/* eslint-enable import/no-extraneous-dependencies */
const capitalizeFirstLetter = (str: string) => str.charAt(0).toUpperCase() + str.slice(1);

const lowercaseFirstLetter = (str: string) => str.charAt(0).toLowerCase() + str.slice(1);

const normalize = (type: string): string => {
  let normalized = type;
  if (type.endsWith("Request")) {
    normalized = type.replace("Request", "");
  } else if (type.endsWith("Response")) {
    normalized = type.replace("Response", "");
  }

  return capitalizeFirstLetter(normalized);
};

const getSubmessageTypes = (interfaceName: string) => {
  const message = file.messages.find((candidate) => candidate.name === interfaceName);
  return message?.fields.flatMap((type) => (type.message?.name ? [type.message.name] : [])) ?? [];
};

const hasRequestFields = (name: string) =>
  Boolean(file.messages.find((message) => message.name === name)?.fields.length);
const requestPayload = (endpoint: string) =>
  hasRequestFields(`${endpoint}Request`)
    ? `Omit<${endpoint}Request, "$typeName" | "$unknown">`
    : "Record<string, never>";

const writeGenericSendRequestWithResponseFunction = (writer: CodeBlockWriter, endpoint: string) => {
  const lowercasedEndpoint = lowercaseFirstLetter(endpoint);

  const template = `export async function send${endpoint}Request(
request: ${requestPayload(endpoint)}
): Promise<${endpoint}Response> {
  return new Promise((resolve, reject) => {
    sendMessage(
      { case: "${lowercasedEndpoint}Request", value: create(${endpoint}RequestSchema, request) },
      (response) => {
        switch (response?.case) {
          case "${lowercasedEndpoint}Response":
            resolve(response.value);
            break;
          case "error":
            reject(Error(response.value));
            break;
          default:
            reject(
              Error(
                  \`Invalid response '\${response?.case}' for '${endpoint}Request'\`
              )
            );
        }
      }
    );
  });
}`;

  writer.writeLine(template).blankLine();
};

const writeGenericSendRequestFunction = (writer: CodeBlockWriter, endpoint: string) => {
  const lowercasedEndpoint = lowercaseFirstLetter(endpoint);

  const template = `export async function send${endpoint}Request(
  request: ${requestPayload(endpoint)}
): Promise<void> {
  return new Promise((resolve, reject) => {
    sendMessage(
      { case: "${lowercasedEndpoint}Request", value: create(${endpoint}RequestSchema, request) },
      (response) => {
        switch (response?.case) {
          case "success":
            resolve();
            break;
          case "error":
            reject(Error(response.value));
            break;
          default:
            reject(
              Error(
                \`Invalid response '\${response?.case}' for '${endpoint}Request'\`
              )
            );
        }
      }
    );
  });
}`;
  writer.writeLine(template).blankLine();
};

const project = new Project({
  manipulationSettings: {
    indentationText: IndentationText.TwoSpaces,
  },
});

project.addSourceFilesAtPaths(join(codegenDirectory, "../src/*.ts"));

const requestTypes = getSubmessageTypes("ClientOriginatedMessage");
const responseTypes = getSubmessageTypes("ServerOriginatedMessage").filter((type) =>
  type.includes("Response"),
);

// Requests deliberately left without a generated wrapper. `getSubmessageTypes` returns *message*
// names, so the previous `request !== "notificationRequest"` filter — comparing against a field
// name — never excluded anything and the wrapper was emitted anyway.
//   NotificationRequest: `notifications.ts` calls `sendMessage` directly.
//   PingRequest:         no caller anywhere in the workspace.
const EXCLUDED_REQUESTS = new Set(["NotificationRequest", "PingRequest"]);

const [requestsWithMatchingResponses, otherRequests] = requestTypes
  .filter((request) => !EXCLUDED_REQUESTS.has(request))
  .reduce(
    (result, request) => {
      const [matchingResponse, other] = result;

      const endpoint = normalize(request);

      console.log(endpoint, requestTypes);

      if (responseTypes.includes(`${endpoint}Response`)) {
        return [matchingResponse.concat([request]), other];
      }
      return [matchingResponse, other.concat([request])];
    },
    [[] as string[], [] as string[]],
  );

console.log(requestsWithMatchingResponses, otherRequests);

const protoVersion = JSON.parse(
  readFileSync(join(codegenDirectory, "../../../proto/package.json"), "utf8"),
).version;

const sourceFile = project.createSourceFile(
  join(codegenDirectory, "../src/requests.ts"),
  (writer) => {
    writer.writeLine(`/* Autogenerated by generate-requests.ts for proto v${protoVersion}`);
    writer.writeLine(
      ` * Do not edit directly! Instead run 'npm run generate-requests' in typescript-api-bindings`,
    );
    writer.writeLine(` */`).blankLine();

    const responses = requestsWithMatchingResponses.map((request) =>
      request.replace("Request", "Response"),
    );
    const requestSchemas = requestsWithMatchingResponses.map((s) => `${s}Schema`);
    const otherRequestSchemas = otherRequests.map((s) => `${s}Schema`);
    // Messages are types, `*Schema` are values: `verbatimModuleSyntax` wants
    // them in separate import statements.
    const typeImports = [
      requestsWithMatchingResponses.filter(hasRequestFields),
      responses,
      otherRequests.filter(hasRequestFields),
    ]
      .flat()
      .toSorted()
      .map(capitalizeFirstLetter);
    const valueImports = [requestSchemas, otherRequestSchemas]
      .flat()
      .toSorted()
      .map(capitalizeFirstLetter);
    writer.writeLine(`import type { \n${typeImports.join(",\n")}\n } from "@fig/proto/fig";`);
    writer.writeLine(`import { \n${valueImports.join(",\n")}\n } from "@fig/proto/fig";`);
    writer
      .writeLine(
        [
          'import { sendMessage } from "./core.js";',
          'import { create } from "@bufbuild/protobuf";',
        ].join("\n"),
      )
      .blankLine();

    requestsWithMatchingResponses.forEach((request) =>
      writeGenericSendRequestWithResponseFunction(writer, normalize(request)),
    );
    otherRequests.forEach((request) => writeGenericSendRequestFunction(writer, normalize(request)));
  },
  { overwrite: true },
);

sourceFile.formatText();
sourceFile.saveSync();
