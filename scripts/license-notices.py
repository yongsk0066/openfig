#!/usr/bin/env python3
"""Rebuild third-party notices from installed, locked macOS dependencies."""
import argparse
import hashlib
import json
from pathlib import Path
import subprocess

ROOT = Path(__file__).resolve().parent.parent
OUTPUT = ROOT / 'packages/dashboard-app/public/license/NOTICE.txt'


def command(*args):
    return json.loads(subprocess.check_output(args, cwd=ROOT, text=True))


def license_files(root):
    # Package-local subdirectories may hold NOTICE, but dependencies are separate entries.
    return sorted(path for path in root.rglob('*') if path.is_file()
                  and 'node_modules' not in path.relative_to(root).parts
                  and path.name.lower().startswith(('license', 'licence', 'notice', 'copying', 'copyright'))
                  and path.suffix.lower() not in ('.rs', '.js', '.ts', '.json', '.html'))


def generate():
    supplements = json.loads((ROOT / 'licenses/sources.json').read_text())
    records = []
    texts = {}

    def add(key, license_id, source, files):
        if not license_id:
            raise ValueError(f'{key}: missing license declaration')
        extra = supplements.get(key)
        if extra:
            files = [*files, ROOT / extra['file']]
        if not files:
            raise ValueError(f'{key}: missing copyright/license text; review and supplement it')
        ids = []
        for path in files:
            text = '\n'.join(line.rstrip() for line in path.read_text().strip().splitlines()) + '\n'
            digest = hashlib.sha256(text.encode()).hexdigest()
            texts[digest] = text
            ids.append(digest)
        records.append((key, license_id, source, sorted(set(ids))))

    metadata = command('cargo', 'metadata', '--locked', '--offline', '--format-version', '1',
                       '--filter-platform', 'aarch64-apple-darwin')
    resolved = {node['id'] for node in metadata['resolve']['nodes']}
    for package in metadata['packages']:
        if package['id'] not in resolved or package['source'] is None:
            continue
        name, version = package['name'], package['version']
        root = Path(package['manifest_path']).parent
        files = license_files(root)
        if package.get('license_file'):
            files = sorted(set([*files, root / package['license_file']]))
        add(f'crate:{name}@{version}', package['license'],
            f'https://crates.io/api/v1/crates/{name}/{version}/download', files)

    packages = command('pnpm', '-r', 'licenses', 'list', '--json')
    seen = set()
    for group in packages.values():
        for package in group:
            for path in package['paths']:
                root = Path(path)
                manifest = json.loads((root / 'package.json').read_text())
                name, version = manifest['name'], manifest['version']
                key = f'npm:{name}@{version}'
                if key in seen:
                    continue
                seen.add(key)
                add(key, package['license'], f'https://registry.npmjs.org/{name}/{version}', license_files(root))

    vendor = [
        ('OpenFig', 'MIT OR Apache-2.0', 'https://github.com/aws/amazon-q-developer-cli-autocomplete',
         [ROOT / 'LICENSE.MIT', ROOT / 'LICENSE.APACHE', ROOT / 'NOTICE']),
        ('accessibility', 'MIT OR Apache-2.0', 'https://github.com/eiz/accessibility',
         license_files(ROOT / 'crates/macos-utils/accessibility-master')),
    ]
    for directory in ['specs', 'packages/fuzzysort', 'packages/spec-types',
                      'packages/spec-generators', 'packages/spec-helpers', 'packages/spec-compiler']:
        source = 'https://github.com/farzher/fuzzysort' if directory.endswith('fuzzysort') else 'https://github.com/withfig/' + ('autocomplete' if directory == 'specs' else 'autocomplete-tools')
        vendor.append((directory, 'MIT', source, [ROOT / directory / 'LICENSE']))
    for name, license_id, source, files in vendor:
        add(f'vendored:{name}', license_id, source, files)

    ids = {digest: f'L{i + 1:04d}' for i, digest in enumerate(sorted(texts))}
    output = ['OpenFig third-party notices', '',
              'Generated by scripts/license-notices.py from the installed locked macOS dependency graph.',
              'Includes build/test tools; presence here does not imply inclusion in the executable.',
              'External components retain their own licenses. Source packages are available at the URLs below.',
              'For MPL-2.0 components, their covered source remains available under MPL-2.0 at those URLs.',
              'Supplement provenance is recorded in licenses/sources.json.', '', 'COMPONENTS', '']
    for key, license_id, source, digests in sorted(records):
        output.extend([key, f'License: {license_id}', f'Source: {source}',
                       'Texts: ' + ', '.join(ids[d] for d in digests), ''])
    output.extend(['LICENSE AND COPYRIGHT TEXTS', ''])
    for digest in sorted(texts):
        output.extend([f'--- {ids[digest]} ---', texts[digest]])
    return '\n'.join(output), len(records)


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    text, count = generate()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text() != text:
            raise SystemExit('Third-party notices are stale; run python3 scripts/license-notices.py')
    else:
        OUTPUT.write_text(text)
    print(f'Third-party notices: {count} components')
